//! Value types shared across uedcli's Rust verbs.

/// A 3D vector or point, matching UnrealEngine's X,Y,Z convention.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Vec3 {
    pub x: f64,
    pub y: f64,
    pub z: f64,
}

impl Vec3 {
    pub fn new(x: f64, y: f64, z: f64) -> Self {
        Vec3 { x, y, z }
    }
}
